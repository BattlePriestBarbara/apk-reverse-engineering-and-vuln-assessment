def sub(old, new, label):
    """唯一命中替换（已应用过则跳过，保证脚本可重跑）。"""
    global text
    if text.count(new) >= 1 and text.count(old) <= text.count(new):
        log.append(label + ":skip")
        return
    if text.count(old) == 0 and text.count(new) >= 1:
        log.append(label + ":skip")
        return
    assert text.count(old) == 1, "%s: count=%d" % (label, text.count(old))
    text = text.replace(old, new, 1)
    log.append(label)


